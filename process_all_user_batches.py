# Parse table lines
entries = []
for line in USER_RAW_MARKDOWN.strip().split('\n'):
    line = line.strip()
    if not line.startswith('|'): continue
    parts = [p.strip() for p in line.split('|')[1:-1]]
    if len(parts) < 6: continue
    paper_str, num_str, qtype_str, topic_str, ans_str, exp_str = parts[:6]
    paper_str = paper_str.replace('*', '')
    num_str = num_str.replace('*', '')
    ans_str = ans_str.replace('*', '').replace(' ', '')
    exp_str = exp_str.replace('\\(', '$').replace('\\)', '$')

    prefix = PAPER_CODE_MAP.get(paper_str)
    if not prefix:
        continue
    
    # Normalize question type in ID
    # In questions_data.js:
    # 2025-813: '不定项', '判断'
    # 2025-815: '多选' or '不定项'
    # 2024-814: '单选' / '多选' / '判断'
    entries.append({
        'prefix': prefix,
        'paper_raw': paper_str,
        'num': int(num_str),
        'qtype_raw': qtype_str,
        'topic': topic_str,
        'ans': ans_str,
        'explanation': exp_str
    })

print(f"Parsed {len(entries)} question entries from user markdown.")

