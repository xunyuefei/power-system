# Check question ID patterns:
matched = 0
for entry in entries:
    prefix = entry['prefix']
    num = entry['num']
    ans = entry['ans']
    exp = entry['explanation']
    topic = entry['topic']

    # Convert answer to list
    if ans in ['√', '×']:
        ans_list = [ans]
    else:
        ans_list = list(ans) # e.g. 'ABC' -> ['A', 'B', 'C']

    # Search for matching question in questions
    # Candidate IDs:
    # f"{prefix}-单选-{num:02d}", f"{prefix}-多选-{num:02d}", f"{prefix}-不定项-{num:02d}", f"{prefix}-判断-{num:02d}", f"{prefix}-选择-{num:02d}"
    candidate_q = None
    for q in questions:
        qid = q['id']
        if not qid.startswith(prefix):
            continue

        # Check if number matches
        m_num = re.search(r'-(\d{2})$', qid)
        if not m_num or int(m_num.group(1)) != num:
            continue

        # Check type match
        is_judge_entry = ('判断' in entry['qtype_raw'] or ans in ['√', '×'])
        is_judge_q = (q.get('type') == 'judge' or '判断' in qid)

        if is_judge_entry == is_judge_q:
            candidate_q = q
            break

    if candidate_q:
        candidate_q['answer'] = ans_list
        candidate_q['answerPending'] = False
        candidate_q['verified'] = True
        candidate_q['topic'] = topic
        candidate_q['explanation'] = exp
        
        # Check controversy note
        if candidate_q['id'] in CONTROVERSY_MAP:
            candidate_q['conflict'] = CONTROVERSY_MAP[candidate_q['id']]

        matched += 1
    else:
        print(f"Warning: Could not match: {prefix} #{num} ({entry['qtype_raw']})")

